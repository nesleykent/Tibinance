import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium, webkit } = require(`${process.env.TIBINANCE_NODE_MODULES}/playwright`);
const engine = process.env.TIBINANCE_BROWSER ?? 'chrome';
const browser = await (engine === 'webkit' ? webkit.launch() : chromium.launch({ channel: 'chrome' }));
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.clock.install({ time: new Date('2026-06-06T12:00:00Z') });
  await page.addInitScript(() => localStorage.setItem('tibinance.markets.dock', ''));
  await page.goto(`${process.env.TIBINANCE_TEST_URL ?? 'http://127.0.0.1:8765'}/markets.html?world=Terribra&range=All`);
  await page.waitForFunction(() => document.querySelector('#market').getAttribute('aria-busy') === 'false');
  await page.click('#eventsToggle');
  assert.equal(await page.getAttribute('#eventsToggle', 'aria-expanded'), 'true');
  assert.equal(await page.locator('#eventAgenda [data-event]').count(), 54, 'the complete world-scoped event history is available by default');
  await page.click('[data-event-section="eventAgendaSection"]');
  await page.click('[data-event-section="eventCalendarSection"]');
  const url = page.url();
  await page.waitForTimeout(250);
  const markerState = () => page.locator('#eventMarks button').evaluateAll(bs => bs.map(b => [b.dataset.events, Math.round(parseFloat(b.style.left))]));
  const markersBefore = await markerState();
  await page.click('[data-month-step="1"]');
  assert.equal(await page.inputValue('#eventMonth'), '2026-07');
  await page.click('[data-month-step="-1"]');
  await page.click('[data-day="2026-06-06"]');
  assert.equal(await page.locator('#eventDayList [data-event]').count(), 2);
  assert.equal(await page.locator('[data-day="2026-06-06"] .event-span').count(), 1);
  await page.locator('#eventDayList [data-event]').first().click();
  assert.match(await page.innerText('#eventDetails'), /2026-06-05 to 2026-06-07/);
  assert.match(await page.innerText('#eventDetails'), /Global: all worlds/);
  assert.equal(page.url(), url);
  assert.deepEqual(await markerState(), markersBefore);
  await page.selectOption('#eventPeriod', 'historical');
  const before = await page.locator('#eventAgenda [data-event]').count();
  await page.selectOption('#eventPeriod', 'all');
  assert.ok(await page.locator('#eventAgenda [data-event]').count() > before);
  await page.selectOption('#eventPeriod', 'upcoming');
  assert.ok(await page.locator('#eventAgenda [data-event]').count() > 0);
  await page.selectOption('#eventPeriod', 'recent');
  assert.ok(await page.locator('#eventAgenda [data-event]').count() > 0);
  await page.selectOption('#eventPeriod', 'all');
  await page.selectOption('#eventCategory', 'rapid-respawn');
  assert.ok((await page.locator('#eventAgenda').innerText()).includes('Rapid Respawn'));
  assert.ok(!(await page.locator('#eventAgenda').innerText()).includes('XP/Skill'));
  await page.selectOption('#eventCategory', '');
  await page.selectOption('#eventScope', 'world');
  await page.selectOption('#eventPeriod', 'all');
  assert.equal(await page.locator('#eventAgenda [data-event]').count(), 2);
  await page.locator('#eventAgenda [data-event]').first().click();
  assert.match(await page.innerText('#eventDetails'), /Terribra/);
  await page.click('#eventFocus');
  await page.waitForTimeout(200);
  assert.match(await page.innerText('#eventFocusStatus'), /Chart focused on 2025-11-06/);
  assert.ok(await page.locator('#eventMarks [data-events~="world-created-2025-11-06-terribra-opened"]').count());
  assert.equal(await page.isVisible('#eventTip'), true);
  await page.uncheck('#eventMarkers');
  assert.equal(await page.locator('#eventMarks button').count(), 0);
  assert.equal(await page.locator('#eventAgenda [data-event]').count(), 2);
  await page.check('#eventMarkers');
  await page.selectOption('#eventScope', '');
  await page.fill('#eventMonth', '2025-11');
  await page.click('[data-day="2025-11-06"]');
  assert.equal(await page.locator('#eventDayList [data-event]').count(), 2);
  await page.locator('#eventDayList [data-event]').last().click();
  await page.locator('#eventsPanel .panel-body').evaluate(e => e.scrollTop = 0);
  await page.mouse.move(20,20);
  await page.screenshot({ path: '/tmp/tibinance-events-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#eventsPanel').scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('#eventDayList [data-event]').last().click();
  await page.click('#eventFocus');
  await page.waitForTimeout(500);
  assert.match(await page.innerText('#eventFocusStatus'), /Chart focused/);
  await page.locator('#eventsPanel').scrollIntoViewIfNeeded();
  await page.locator('#eventCalendar').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/tibinance-events-phone.png' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(`${process.env.TIBINANCE_TEST_URL ?? 'http://127.0.0.1:8765'}/markets.html?world=Luzibra&range=All`);
  await page.waitForFunction(() => document.querySelector('#market').getAttribute('aria-busy') === 'false');
  await page.click('#eventsToggle');
  await page.selectOption('#eventPeriod', 'all');
  await page.selectOption('#eventScope', 'world');
  assert.match(await page.innerText('#eventsContext'), /Luzibra/);
  assert.match(await page.innerText('#eventAgenda'), /Merge announced/);
  assert.doesNotMatch(await page.innerText('#eventAgenda'), /Terribra opened/);
  await page.selectOption('#eventScope', 'global');
  await page.locator('#eventAgenda [data-event]').first().focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#eventAgenda [aria-pressed="true"]').count(), 1);
  await page.click('#eventFocus');
  await page.waitForTimeout(200);
  assert.ok(await page.locator('#eventMarks button').count() > 0, 'events before market history extend the date axis');
  assert.match(await page.innerText('#eventDetails'), /Global: all worlds/);
  assert.deepEqual(errors, []);
  console.log(`Events panel browser checks passed (${engine}).`);
} finally { await browser.close(); }
